"use client";

import { DESKTOP_PROJECT_ID, isTauriEnvironment } from "@/lib/tauri";
import { LOCAL_DESKTOP_USER } from "@/lib/desktop-auth";
import type { Project } from "@/types/database";

/**
 * Local-first projects.
 *
 * A `local-…` id never touches Supabase: its metadata lives in `localStorage`
 * and its media/autosaves live in IndexedDB under the same id, using the exact
 * same persistence path as a cloud project. This powers the landing page's
 * "Try in Browser" demo, the Project Manager dashboard, and the Tauri desktop
 * app.
 */

const ACTIVE_PROJECT_KEY = "forgevyn:active-project";
const REGISTRY_KEY = "forgevyn:local-projects";
const TITLE_PREFIX = "forgevyn:project-title:";

export const LOCAL_PROJECT_PREFIX = "local-";
export const DEMO_PROJECT_TITLE = "Browser Demo Project";
export const DESKTOP_PROJECT_TITLE = "Desktop Project";

export type LocalStorageMode = "app" | "custom" | "desktop" | "browser";

export type LocalProjectRecord = {
  id: string;
  title: string;
  createdAt: number;
  updatedAt: number;
  storageMode: LocalStorageMode;
  /** Project root chosen by the user (desktop only). */
  rootPath?: string;
  /** `<root>/.forgevyn/project.forgevyn` (desktop only). */
  manifestPath?: string;
  status?: string;
};

/** True for ids generated by {@link createLocalProject}. */
export function isLocalProjectId(
  id: string | null | undefined
): id is string {
  return typeof id === "string" && id.startsWith(LOCAL_PROJECT_PREFIX);
}

function readStorage(key: string): string | null {
  if (typeof window === "undefined") return null;
  try {
    return window.localStorage.getItem(key);
  } catch {
    return null;
  }
}

function writeStorage(key: string, value: string): void {
  if (typeof window === "undefined") return;
  try {
    window.localStorage.setItem(key, value);
  } catch {
    // Private mode / quota — the session still works in memory.
  }
}

function removeStorage(key: string): void {
  if (typeof window === "undefined") return;
  try {
    window.localStorage.removeItem(key);
  } catch {
    // ignore
  }
}

function readRegistry(): LocalProjectRecord[] {
  const raw = readStorage(REGISTRY_KEY);
  if (!raw) return [];
  try {
    const parsed: unknown = JSON.parse(raw);
    if (!Array.isArray(parsed)) return [];
    return parsed.filter((item): item is LocalProjectRecord => {
      if (!item || typeof item !== "object") return false;
      const record = item as Partial<LocalProjectRecord>;
      return typeof record.id === "string" && isLocalProjectId(record.id);
    });
  } catch {
    return [];
  }
}

function writeRegistry(records: LocalProjectRecord[]): void {
  writeStorage(REGISTRY_KEY, JSON.stringify(records));
}

function defaultTitle(): string {
  return isTauriEnvironment() ? DESKTOP_PROJECT_TITLE : DEMO_PROJECT_TITLE;
}

function ensureRecord(id: string): LocalProjectRecord {
  const records = readRegistry();
  const existing = records.find((record) => record.id === id);
  if (existing) return existing;

  const now = Date.now();
  const record: LocalProjectRecord = {
    id,
    title: readStorage(`${TITLE_PREFIX}${id}`) || defaultTitle(),
    createdAt: now,
    updatedAt: now,
    storageMode: isTauriEnvironment() ? "app" : "browser",
    status: "in-progress",
  };
  writeRegistry([record, ...records]);
  return record;
}

/** The last browser/desktop project this device opened, or null. */
export function activeLocalProjectId(): string | null {
  const id = readStorage(ACTIVE_PROJECT_KEY);
  return isLocalProjectId(id) ? id : null;
}

/** Remembers the browser project so the next visit reopens it. */
export function rememberLocalProject(id: string): void {
  if (!isLocalProjectId(id)) return;
  writeStorage(ACTIVE_PROJECT_KEY, id);
  ensureRecord(id);
}

/** Clears the remembered project without deleting its data. */
export function clearActiveLocalProject(): void {
  removeStorage(ACTIVE_PROJECT_KEY);
}

/** Reads one project record, migrating the remembered project if needed. */
export function getLocalProjectRecord(
  id: string | null | undefined
): LocalProjectRecord | null {
  if (!isLocalProjectId(id)) return null;
  const existing = readRegistry().find((record) => record.id === id);
  return existing ?? ensureRecord(id);
}

/** All local project records, newest edit first. */
export function listLocalProjectRecords(): LocalProjectRecord[] {
  const records = readRegistry();
  const active = activeLocalProjectId();
  if (active && !records.some((record) => record.id === active)) {
    records.push(ensureRecord(active));
  }
  return [...records].sort((a, b) => b.updatedAt - a.updatedAt);
}

/** Synthesized `Project` rows for dashboards and lists. */
export function listLocalProjects(): Project[] {
  return listLocalProjectRecords().map(recordToProject);
}

function recordToProject(record: LocalProjectRecord): Project {
  return {
    id: record.id,
    user_id: isTauriEnvironment() ? LOCAL_DESKTOP_USER.id : "local-browser",
    channel_id: null,
    title: record.title,
    status: record.status || "in-progress",
    settings: {
      local: true,
      storageMode: record.storageMode,
      rootPath: record.rootPath,
      manifestPath: record.manifestPath,
    },
    created_at: new Date(record.createdAt).toISOString(),
    updated_at: new Date(record.updatedAt).toISOString(),
  };
}

/** Creates and remembers a new local project. */
export function createLocalProject(input: {
  title: string;
  storageMode?: LocalStorageMode;
  rootPath?: string;
  manifestPath?: string;
  status?: string;
}): string {
  const id = `${LOCAL_PROJECT_PREFIX}${Date.now().toString(36)}${Math.random()
    .toString(36)
    .slice(2, 6)}`;
  const now = Date.now();
  const title = input.title.trim() || "Untitled Project";
  const records = readRegistry().filter((record) => record.id !== id);
  const record: LocalProjectRecord = {
    id,
    title,
    createdAt: now,
    updatedAt: now,
    storageMode: input.storageMode ?? (isTauriEnvironment() ? "app" : "browser"),
    rootPath: input.rootPath,
    manifestPath: input.manifestPath,
    status: input.status ?? "draft",
  };
  writeRegistry([record, ...records]);
  writeStorage(`${TITLE_PREFIX}${id}`, title);
  writeStorage(ACTIVE_PROJECT_KEY, id);
  return id;
}

/** Updates a local project record without touching its media. */
export function updateLocalProjectRecord(
  id: string,
  patch: Partial<Omit<LocalProjectRecord, "id">>
): LocalProjectRecord | null {
  if (!isLocalProjectId(id)) return null;
  const records = readRegistry();
  const index = records.findIndex((record) => record.id === id);
  const current = index >= 0 ? records[index] : ensureRecord(id);
  const next: LocalProjectRecord = {
    ...current,
    ...patch,
    id,
    updatedAt: patch.updatedAt ?? Date.now(),
  };
  if (index >= 0) records[index] = next;
  else records.unshift(next);
  writeRegistry(records);
  if (patch.title) writeStorage(`${TITLE_PREFIX}${id}`, patch.title);
  return next;
}

/** Marks a project as edited (updates dashboard sort order). */
export function touchLocalProject(id: string): void {
  updateLocalProjectRecord(id, { updatedAt: Date.now() });
}

/** Removes only local metadata; media cleanup remains the caller's choice. */
export function deleteLocalProject(id: string): void {
  if (!isLocalProjectId(id)) return;
  writeRegistry(readRegistry().filter((record) => record.id !== id));
  removeStorage(`${TITLE_PREFIX}${id}`);
  if (activeLocalProjectId() === id) removeStorage(ACTIVE_PROJECT_KEY);
}

/** Title for a browser project (editable, persisted locally). */
export function localProjectTitle(id: string): string {
  const record = readRegistry().find((item) => item.id === id);
  if (record) return record.title;
  const stored = readStorage(`${TITLE_PREFIX}${id}`);
  if (stored) return stored;
  return defaultTitle();
}

/** Persists an inline title edit for a browser project. */
export function renameLocalProject(id: string, title: string): void {
  writeStorage(`${TITLE_PREFIX}${id}`, title);
  updateLocalProjectRecord(id, { title });
}

/** Synthesizes the `Project` row the editor expects, without any network call. */
export function buildLocalProject(id: string): Project {
  const record = getLocalProjectRecord(id);
  if (record) return recordToProject(record);
  const now = new Date().toISOString();
  return {
    id,
    user_id: isTauriEnvironment() ? LOCAL_DESKTOP_USER.id : "local-browser",
    channel_id: null,
    title: localProjectTitle(id),
    status: "in-progress",
    settings: { local: true },
    created_at: now,
    updated_at: now,
  };
}

/**
 * Returns the remembered local project, or creates one on first launch.
 *
 * Existing desktop installs keep their remembered id. A fresh install gets a
 * new project record; the Project Manager dashboard is the normal first boot.
 */
export function getOrCreateLocalProject(): string {
  const existing = activeLocalProjectId();
  if (existing) {
    ensureRecord(existing);
    return existing;
  }

  // Preserve the legacy desktop demo bucket if it has actually been used.
  if (
    isTauriEnvironment() &&
    readRegistry().some((record) => record.id === DESKTOP_PROJECT_ID)
  ) {
    rememberLocalProject(DESKTOP_PROJECT_ID);
    return DESKTOP_PROJECT_ID;
  }

  return createLocalProject({
    title: defaultTitle(),
    storageMode: isTauriEnvironment() ? "app" : "browser",
  });
}
